<?php

namespace App\Http\Resources\Api;

use Illuminate\Http\Request;
use Illuminate\Http\Resources\Json\JsonResource;

class UserResource extends JsonResource
{
    /**
     * Transform the resource into an array with strict sensitive field filtering.
     * Passwords, remember tokens, MFA secrets, recovery codes, and lockout counters
     * are strictly excluded to prevent data exposure.
     */
    public function toArray(Request $request): array
    {
        return [
            'id' => $this->id,
            'name' => $this->name,
            'email' => $this->email,
            'role' => $this->role,
            'phone' => $this->when($request->user()?->id === $this->id || $request->user()?->role === 'admin', $this->phone),
            'avatar' => $this->avatar,
            'is_active' => (bool) $this->is_active,
            'created_at' => $this->created_at?->toIso8601String(),
            'updated_at' => $this->updated_at?->toIso8601String(),
        ];
    }
}

