    /**
     * Admin Agreement Management Dashboard
     */
    public function index(Request $request)
    {
        // 1. Dashboard Metrics Counters
        $metrics = [
            'total' => Agreement::count(),
            'draft' => Agreement::where('status', 'draft')->count(),
            'pending_signature' => Agreement::where('status', 'pending_signature')->count(),
            'fully_signed' => Agreement::where('status', 'fully_signed')->count(),
            'estamp_pending' => Agreement::where('status', 'estamp_pending')->count(),
            'active' => Agreement::where('status', 'active')->count(),
            'expired' => Agreement::where('status', 'expired')->count(),
            'cancelled' => Agreement::where('status', 'cancelled')->count(),
            'total_value' => Agreement::whereNotIn('status', ['cancelled', 'expired'])->sum('contract_value'),
        ];

        // 2. Query with search and status filtering
        $query = Agreement::with(['template', 'creator'])->latest();

        if ($request->filled('status') && $request->input('status') !== 'all') {
            $query->where('status', $request->input('status'));
        }

        if ($request->filled('search')) {
            $s = \App\Security\UrlValidator::escapeLike((string) $request->input('search'));
            $query->where(function ($q) use ($s) {
                $q->where('agreement_number', 'like', "%{$s}%")
                  ->orWhere('title', 'like', "%{$s}%")
                  ->orWhere('client_name', 'like', "%{$s}%")
                  ->orWhere('client_email', 'like', "%{$s}%")
                  ->orWhere('client_company', 'like', "%{$s}%");
            });
        }

        $agreements = $query->paginate(10)->withQueryString();

        return view('admin.agreements.index', compact('metrics', 'agreements'));
    }

