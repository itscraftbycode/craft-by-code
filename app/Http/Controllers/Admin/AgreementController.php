    /**
     * Store New Agreement in Database
     */
    public function store(Request $request)
    {
        $validated = $request->validate([
            'title' => 'required|string|max:200',
            'template_id' => 'nullable|exists:agreement_templates,id',
            'client_name' => 'required|string|max:120',
            'client_email' => 'required|email|max:150',
            'client_company' => 'nullable|string|max:150',
            'client_phone' => 'nullable|string|max:30',
            'client_address' => 'nullable|string|max:500',
            'contract_value' => 'required|numeric|min:0|max:999999999',
            'currency' => 'required|string|size:3',
            'start_date' => 'nullable|date',
            'end_date' => 'nullable|date|after_or_equal:start_date',
            'scope_of_work' => 'nullable|string',
            'payment_terms' => 'nullable|string',
            'content' => 'required|string',
        ]);

        $agreement = new Agreement($validated);
        $agreement->agreement_number = Agreement::generateNextNumber();
        $agreement->status = 'draft';
        $agreement->created_by = Auth::id();
        $agreement->save();

        $authorName = Auth::user()?->name ?? 'Admin';
        $actorPrefix = str_starts_with($authorName, 'Admin') ? $authorName : "Admin {$authorName}";

        AgreementAuditLog::log(
            $agreement,
            'created',
            "Agreement {$agreement->agreement_number} generated by {$actorPrefix}.",
            ['status' => 'draft', 'contract_value' => $agreement->contract_value]
        );

        // Auto-generate initial PDF draft
        try {
            $this->pdfService->generate($agreement);
        } catch (\Throwable $e) {
            // PDF compilation will be retryable on show page
        }

        return redirect()->route('admin.agreements.show', $agreement->id)
            ->with('success', "Agreement {$agreement->agreement_number} created successfully.");
    }

