    /**
     * Apply Cryptographic Digital Signature (Admin Only)
     */
    public function applyDigitalSignature(Request $request, Agreement $agreement)
    {
        $validated = $request->validate([
            'signatory_role' => 'required|string|max:100',
            'notes' => 'nullable|string|max:255',
        ]);

        $admin = Auth::user();
        $timestamp = now();

        $signaturePayload = implode('|', [
            $agreement->agreement_number,
            $agreement->client_email,
            $agreement->contract_value,
            $admin->email,
            $timestamp->timestamp,
            config('app.key'),
        ]);

        $sigHash = hash_hmac('sha256', $signaturePayload, (string) config('app.key'));

        $metadata = [
            'signed_by' => $admin->name,
            'signatory_email' => $admin->email,
            'signatory_role' => $validated['signatory_role'],
            'signer_ip' => $request->ip(),
            'user_agent' => $request->userAgent(),
            'timestamp' => $timestamp->toIso8601String(),
            'algorithm' => 'HMAC-SHA256',
            'notes' => $validated['notes'] ?? null,
        ];

        // Determine next status
        $nextStatus = empty($agreement->estamp_number) ? 'fully_signed' : 'active';

        $agreement->update([
            'digital_signature_hash' => $sigHash,
            'digital_signature_metadata' => $metadata,
            'signed_at' => $timestamp,
            'status' => $nextStatus,
            'updated_by' => $admin->id,
        ]);

        AgreementAuditLog::log(
            $agreement,
            'digitally_signed',
            "Digital signature stamped by {$admin->name} ({$validated['signatory_role']}). Hash: " . substr($sigHash, 0, 16) . "...",
            ['signature_hash' => $sigHash, 'status' => $nextStatus]
        );

        // Recompile official PDF with signature block
        $this->pdfService->generate($agreement);

        return back()->with('success', 'Digital signature successfully applied and stamped onto agreement PDF.');
    }

    /**
     * Attach & Manage e-Stamp Certificate (Admin Only)
     */
    public function attachEstamp(Request $request, Agreement $agreement)
    {
        $validated = $request->validate([
            'estamp_number' => 'required|string|max:80',
            'estamp_state' => 'required|string|max:80',
            'estamp_amount' => 'required|numeric|min:0',
            'estamp_issued_at' => 'required|date',
            'certificate_file' => 'nullable|file|mimes:pdf,jpg,jpeg,png|max:5120',
        ]);

        $certPath = $agreement->estamp_certificate_path;
        if ($request->hasFile('certificate_file')) {
            $file = $request->file('certificate_file');
            $certPath = $file->store('private/agreements/estamps', 'local');
        }

        // If agreement already signed, it can move to active
        $nextStatus = $agreement->hasDigitalSignature() ? 'active' : 'estamp_pending';

        $agreement->update([
            'estamp_number' => $validated['estamp_number'],
            'estamp_state' => $validated['estamp_state'],
            'estamp_amount' => $validated['estamp_amount'],
            'estamp_issued_at' => $validated['estamp_issued_at'],
            'estamp_certificate_path' => $certPath,
            'status' => $agreement->status === 'draft' ? $nextStatus : $agreement->status,
            'updated_by' => Auth::id(),
        ]);

        AgreementAuditLog::log(
            $agreement,
            'estamp_attached',
            "E-Stamp Certificate {$validated['estamp_number']} ({$validated['estamp_state']}) attached.",
            ['estamp_number' => $validated['estamp_number'], 'amount' => $validated['estamp_amount']]
        );

        // Recompile PDF with e-Stamp endorsement
        $this->pdfService->generate($agreement);

        return back()->with('success', 'e-Stamp certificate attached and endorsed successfully.');
    }

    /**
     * Update Agreement Status (Approve, Finalize, Cancel)
     */
    public function updateStatus(Request $request, Agreement $agreement)
    {
        $validated = $request->validate([
            'status' => 'required|in:draft,pending_signature,fully_signed,estamp_pending,active,completed,expired,cancelled',
            'cancellation_reason' => 'required_if:status,cancelled|nullable|string|max:500',
        ]);

        $oldStatus = $agreement->status;
        $newStatus = $validated['status'];

        $updates = [
            'status' => $newStatus,
            'updated_by' => Auth::id(),
        ];

        if ($newStatus === 'cancelled') {
            $updates['cancelled_at'] = now();
            $updates['cancellation_reason'] = $validated['cancellation_reason'] ?? 'Cancelled by Admin';
        } elseif ($newStatus === 'completed' || $newStatus === 'active') {
            $updates['finalized_at'] = $agreement->finalized_at ?? now();
        }

        $agreement->update($updates);

        AgreementAuditLog::log(
            $agreement,
            'status_changed',
            "Status transitioned from '{$oldStatus}' to '{$newStatus}'.",
            ['old_status' => $oldStatus, 'new_status' => $newStatus]
        );

        // Recompile PDF to reflect status banner
        $this->pdfService->generate($agreement);

        return back()->with('success', "Agreement status updated to '" . ucfirst(str_replace('_', ' ', $newStatus)) . "'.");
    }

